func (s *Server) Handler() http.Handler { return s.requireAuth(s.mux) }

func writeJSON(w http.ResponseWriter, code int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(code)
	_ = json.NewEncoder(w).Encode(v)
}

func (s *Server) healthz(w http.ResponseWriter, _ *http.Request) {
	// version is unauthenticated (already in -version and the support bundle):
	// the update health-probe reads it to confirm the NEW binary is the one now
	// serving before clearing the pending-update marker.
	writeJSON(w, 200, map[string]any{"ok": true, "ts": time.Now().UTC(), "version": s.version})
}

// metrics emits Prometheus text format by hand — a handful of gauges
// doesn't justify the client_golang dependency tree. Job counters are
// derived from the DB at scrape time (restart-proof); pool and drive
// series carry pool/library labels from the start so a second pool
// or library won't break dashboards.
func (s *Server) metrics(w http.ResponseWriter, r *http.Request) {
	snap := s.inv.Snapshot()
	w.Header().Set("Content-Type", "text/plain; version=0.0.4")
	p := func(format string, a ...any) { fmt.Fprintf(w, format+"\n", a...) }

	// ZFS storage plane (v0.7): per-pool filesystem + logical (pre-dedup/
	// compress) sizes, per-dataset compression, and the pool-wide dedupe
	// ratio (the shared dedup vdev serves every dataset).
	p("# TYPE openvtl_pool_fs_used_bytes gauge")
	p("# TYPE openvtl_pool_fs_total_bytes gauge")
	p("# TYPE openvtl_pool_logical_bytes gauge")
	p("# TYPE openvtl_pool_dedup_ratio gauge")
	p("# TYPE openvtl_pool_compress_ratio gauge")
	// phys_est ≈ dataset used ÷ global dedupratio — the honest per-pool
	// disk share (fs_used is post-compression only and exceeds the pool
	// size under heavy dedup); the zpool gauges are the real fill level.
	p("# TYPE openvtl_pool_phys_est_bytes gauge")
	p("# TYPE openvtl_zpool_alloc_bytes gauge")
	p("# TYPE openvtl_zpool_size_bytes gauge")
	for i, pool := range snap.Pools {
		p(`openvtl_pool_fs_used_bytes{pool=%q} %d`, pool.Name, pool.FSUsedBytes)
		p(`openvtl_pool_fs_total_bytes{pool=%q} %d`, pool.Name, pool.FSTotalBytes)
		p(`openvtl_pool_logical_bytes{pool=%q} %d`, pool.Name, pool.LogicalBytes)
		p(`openvtl_pool_dedup_ratio{pool=%q} %.3f`, pool.Name, pool.DedupRatio)
		p(`openvtl_pool_compress_ratio{pool=%q} %.3f`, pool.Name, pool.CompressRatio)
		p(`openvtl_pool_phys_est_bytes{pool=%q} %d`, pool.Name, pool.PhysEstBytes)
		if i == 0 { // zpool figures are system-wide (identical on every pool)
			p(`openvtl_zpool_alloc_bytes %d`, pool.ZpoolAllocBytes)
			p(`openvtl_zpool_size_bytes %d`, pool.ZpoolSizeBytes)
		}
	}

	p("# TYPE openvtl_fc_target_verified gauge")
	v := 0
	if snap.FC.Verified {
		v = 1
	}
	p("openvtl_fc_target_verified %d", v)

	serialOf := map[int]string{}
	p("# TYPE openvtl_drive_blocks_written counter")
	p("# TYPE openvtl_drive_blocks_read counter")
	for _, l := range snap.Libraries {
		serialOf[l.Library.ID] = l.Library.Serial
		for _, d := range l.Drives {
			p(`openvtl_drive_blocks_written{library=%q,drive="%d"} %d`, l.Library.Serial, d.Index, d.BlocksWritten)
			p(`openvtl_drive_blocks_read{library=%q,drive="%d"} %d`, l.Library.Serial, d.Index, d.BlocksRead)
		}
	}

	// Job outcomes/bytes/durations — the v0.5 "Grafana-able" additions.
	if stats, err := s.db.JobStats(r.Context()); err == nil {
		p("# TYPE openvtl_jobs_total counter")
		p("# TYPE openvtl_job_bytes_total counter")
		p("# TYPE openvtl_job_duration_seconds_total counter")
		for _, j := range stats {
			p(`openvtl_jobs_total{kind=%q,outcome=%q} %d`, j.Kind, j.Outcome, j.Count)
			p(`openvtl_job_bytes_total{kind=%q,outcome=%q} %d`, j.Kind, j.Outcome, j.Bytes)
			p(`openvtl_job_duration_seconds_total{kind=%q,outcome=%q} %d`, j.Kind, j.Outcome, j.DurationSec)
		}
	}
	if counts, err := s.db.CartStateCounts(r.Context()); err == nil {
		p("# TYPE openvtl_carts gauge")
		for _, c := range counts {
			p(`openvtl_carts{library=%q,local_state=%q} %d`, serialOf[c.LibraryID], c.LocalState, c.Count)
		}
	}
	// Live initiator logins (configfs/sysfs reads — cheap on the
	// scrape path). Per-fabric since v0.7's multi-port registry.
	byFabric := map[string]int{}
	for _, iv := range s.fc.Initiators(r.Context()) {
		if iv.LoggedIn {
			byFabric[iv.Fabric]++
		}
	}
	p("# TYPE openvtl_target_sessions_active gauge")
	for fabric, n := range byFabric {
		p(`openvtl_target_sessions_active{fabric=%q} %d`, fabric, n)
	}
}

// libraryOut / librarySnapOut decorate the live snapshot with the
// persisted display name (v0.7: names shown everywhere, serial stays
// the host-facing identity as subtext).
type libraryOut struct {
	inventory.Library
	Name string `json:"name"`
}

type librarySnapOut struct {
	inventory.LibrarySnapshot
	Library libraryOut `json:"library"`
}

// fabricsOut feeds the header's aggregate fabric chip: FC state + live
// session count in one glance (additive; snapshot.fc unchanged).
type fabricsOut struct {
	FC struct {
		Present  bool   `json:"present"`
		Verified bool   `json:"verified"`
		Detail   string `json:"detail"`
		Sessions int    `json:"sessions"`
	} `json:"fc"`
}

func (s *Server) status(w http.ResponseWriter, r *http.Request) {
	// The outer fields shadow Snapshot's (shallower depth wins in
	// encoding/json): Carts carries the same local_state /
	// last_export_gen join as /api/cartridges, Libraries the display
	// names. Initiators is a configfs/sysfs read — cheap on this path
	// (same reasoning as /metrics).
	snap := s.inv.Snapshot()
	names := map[int]string{}
	if rows, err := s.db.ListLibraries(r.Context()); err == nil {
		for _, l := range rows {
			names[l.ID] = l.Name
		}
	}
	libs := make([]librarySnapOut, 0, len(snap.Libraries))
	for _, l := range snap.Libraries {
		name := names[l.Library.ID]
		if name == "" {
			name = l.Library.Serial
		}
		libs = append(libs, librarySnapOut{LibrarySnapshot: l, Library: libraryOut{Library: l.Library, Name: name}})
	}

	// FC presence comes from the live fc_host port count — the
	// snapshot's FCState is the aggregate target state.
	var fab fabricsOut
	fab.FC.Present, fab.FC.Verified, fab.FC.Detail = s.fc.HBAPresent(), snap.FC.Verified, snap.FC.Detail
	for _, iv := range s.fc.Initiators(r.Context()) {
		if iv.LoggedIn {
			fab.FC.Sessions++
		}
	}

	writeJSON(w, 200, struct {
		inventory.Snapshot
		Libraries []librarySnapOut `json:"libraries"`
		Carts     []cartOut        `json:"cartridges"`
		Fabrics   fabricsOut       `json:"fabrics"`
	}{snap, libs, s.cartsWithMeta(r), fab})
}

func (s *Server) library(w http.ResponseWriter, _ *http.Request) {
	writeJSON(w, 200, map[string]any{
		"libraries": s.inv.Snapshot().Libraries,
	})
}

// cartOut joins live inventory with persisted per-cart state (eviction
// stubs, last export generation).
type cartOut struct {
	inventory.Cart
	LocalState    string `json:"local_state"`
	LastExportGen string `json:"last_export_gen,omitempty"`
}

func (s *Server) cartsWithMeta(r *http.Request) []cartOut {
	metas, err := s.db.CartMetas(r.Context())
	if err != nil {
		s.log.Warn("cart metas", "err", err)
	}
	carts := s.inv.Snapshot().AllCarts()
	out := make([]cartOut, 0, len(carts))
	for _, c := range carts {
		co := cartOut{Cart: c, LocalState: "resident"}
		if m, ok := metas[c.Label]; ok {
			co.LocalState, co.LastExportGen = m.LocalState, m.LastExportGen
		}
		out = append(out, co)
	}
	return out
}

func (s *Server) cartridges(w http.ResponseWriter, r *http.Request) {
	writeJSON(w, 200, s.cartsWithMeta(r))
}

func (s *Server) cartridge(w http.ResponseWriter, r *http.Request) {
	label := r.PathValue("label")
	for _, c := range s.cartsWithMeta(r) {
		if c.Label == label {
			writeJSON(w, 200, c)
			return
		}
	}
	writeJSON(w, 404, map[string]string{"error": "unknown cartridge"})
}

// poolHistory serves persisted dedupe_stats samples so the dashboard
// capacity trend survives restarts (v0.4's was session-only). ?pool=
// selects a pool; default is the first in the snapshot (legacy series
// name pre-rebuild).
func (s *Server) poolHistory(w http.ResponseWriter, r *http.Request) {
	hours := 24
	if h, err := strconv.Atoi(r.URL.Query().Get("hours")); err == nil && h > 0 && h <= 24*90 {
		hours = h
	}
	pool := r.URL.Query().Get("pool")
	if pool == "" {
		if pools := s.inv.Snapshot().Pools; len(pools) > 0 {
			pool = pools[0].Name
		} else {
			pool = s.cfg.VDOLV
		}
	}
	samples, err := s.db.PoolHistory(r.Context(), pool, time.Now().Add(-time.Duration(hours)*time.Hour))
	if err != nil {
		serverError(w, err)
		return
	}
	if samples == nil {
		samples = []store.PoolSample{}
	}
	writeJSON(w, 200, samples)
}

