// searchEvents runs a deep query over the whole persisted event_log — a
// free-text match (q) and/or an exact kind, newest first. The journal
// viewer uses it to reach past the 200-row recent window.
func (s *Server) searchEvents(w http.ResponseWriter, r *http.Request) {
	q := strings.TrimSpace(r.URL.Query().Get("q"))
	kind := r.URL.Query().Get("kind")
	if kind == "all" {
		kind = ""
	}
	limit := 500
	if v := r.URL.Query().Get("limit"); v != "" {
		if n, err := strconv.Atoi(v); err == nil {
			limit = n
		}
	}
	evs, err := s.db.SearchEvents(r.Context(), q, kind, limit)
	if err != nil {
		writeJSON(w, 500, map[string]string{"error": err.Error()})
		return
	}
	writeJSON(w, 200, evs)
}

// sse streams the event bus. Clients resync full state from /api/status
// on (re)connect; the stream carries diffs.
func (s *Server) sse(w http.ResponseWriter, r *http.Request) {
	fl, ok := w.(http.Flusher)
	if !ok {
		http.Error(w, "streaming unsupported", 500)
		return
	}
	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	w.Header().Set("Connection", "keep-alive")

	ch, cancel := s.bus.Subscribe()
	defer cancel()
	keep := time.NewTicker(20 * time.Second)
	defer keep.Stop()

	fmt.Fprint(w, ": connected\n\n")
	fl.Flush()
	for {
		select {
		case <-r.Context().Done():
			return
		case <-keep.C:
			fmt.Fprint(w, ": keepalive\n\n")
			fl.Flush()
		case ev, ok := <-ch:
			if !ok {
				return
			}
			fmt.Fprintf(w, "event: %s\ndata: %s\n\n", ev.Kind, ev.JSON())
			fl.Flush()
		}
	}
}

// static serves the embedded SPA with index.html fallback for client routes.
func (s *Server) static(w http.ResponseWriter, r *http.Request) {
	path := strings.TrimPrefix(r.URL.Path, "/")
	if path == "" {
		path = "index.html"
	}
	if _, err := fs.Stat(s.ui, path); err != nil {
		path = "index.html" // SPA fallback
	}
	http.ServeFileFS(w, r, s.ui, path)
}

// ListenAndServe runs the HTTPS API (and, when plainAddr is non-empty,
// a plaintext sidecar serving only /healthz + /metrics and redirecting
// the rest) until ctx is cancelled. The plaintext listener is optional
// by requirement — HTTPS-only sites pass -listen "".
func (s *Server) ListenAndServe(ctx context.Context, tlsAddr, certFile, keyFile, plainAddr string) error {
	srv := &http.Server{Addr: tlsAddr, Handler: s.Handler()}
	errCh := make(chan error, 2)
	go func() { errCh <- srv.ListenAndServeTLS(certFile, keyFile) }()
	s.log.Info("API listening (TLS)", "addr", tlsAddr)

	var plain *http.Server
	if plainAddr != "" {
		plain = &http.Server{Addr: plainAddr, Handler: s.plainHandler(tlsAddr)}
		go func() { errCh <- plain.ListenAndServe() }()
		s.log.Info("plaintext listener (metrics/health + redirect)", "addr", plainAddr)
	}

	shutdown := func() {
		sctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()
		srv.Shutdown(sctx)
		if plain != nil {
			plain.Shutdown(sctx)
		}
	}
	select {
	case <-ctx.Done():
		shutdown()
		return nil
	case err := <-errCh:
		shutdown()
		return err
	}
}

// plainHandler is the whole surface of the optional HTTP listener:
// scrape + health stay plaintext for tooling, everything else is sent
// to the TLS port.
func (s *Server) plainHandler(tlsAddr string) http.Handler {
	_, tlsPort, err := net.SplitHostPort(tlsAddr)
	if err != nil {
		tlsPort = "8443"
	}
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/healthz":
			s.healthz(w, r)
		case "/metrics":
			s.metrics(w, r)
		default:
			host := r.Host
			if h, _, err := net.SplitHostPort(host); err == nil {
				host = h
			}
			http.Redirect(w, r, "https://"+net.JoinHostPort(host, tlsPort)+r.URL.RequestURI(), http.StatusPermanentRedirect)
		}
	})
}
