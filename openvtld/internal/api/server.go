type Server struct {
	cfg       *config.Config
	inv       *inventory.Engine
	bus       *events.Bus
	db        *store.Store
	runner    *export.Runner
	fc        *orchestrate.FC
	stor      *storage.Manager
	log       *slog.Logger
	ui        fs.FS
	mux       *http.ServeMux
	version   string
	buildDate string // ldflags buildDate — the update-ordering key
	started   time.Time

	// setupDone latches true once the first admin exists; until then the
	// middleware answers 409 setup_required to everything but setup.
	setupDone atomic.Bool
	// draining: a graceful restart is waiting for jobs to finish; new
	// job-creating calls are refused until it fires or times out.
	draining atomic.Bool
	// mintMu serializes cart creation so concurrent requests can't
	// allocate the same autogenerated label from equal snapshots.
	mintMu sync.Mutex
}

